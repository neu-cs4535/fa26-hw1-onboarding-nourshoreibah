CREATE TRIGGER broadcast_gradebook_column_groups_unified
  AFTER INSERT OR UPDATE OR DELETE ON public.gradebook_column_groups
  FOR EACH ROW EXECUTE FUNCTION public.broadcast_gradebook_column_groups_change();

