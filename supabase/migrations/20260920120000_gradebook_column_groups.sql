-- One group per legacy run. A group's slug is its base, slugified (average.hw becomes
-- average-hw); the second run of the same base gets -2, and so on. Slug routing names new groups
-- the same way, so an expression can say gradebook_column_group("quiz") whichever made the group.
CREATE TEMP TABLE _cg_phase_one_groups (
  gradebook_id bigint,
  group_index  bigint,
  group_id     bigint NOT NULL,
  PRIMARY KEY (gradebook_id, group_index)
);

DO $$
DECLARE
  r    record;
  v_id bigint;
BEGIN
  FOR r IN
    SELECT DISTINCT ON (l.gradebook_id, l.group_index) l.gradebook_id, l.class_id, l.group_index, l.base
      FROM public.gradebook_column_legacy_groups l
     ORDER BY l.gradebook_id, l.group_index, l.so, l.id
  LOOP
    INSERT INTO public.gradebook_column_groups
           (class_id, gradebook_id, name, slug, sort_order, auto_assign_slug_base)
    VALUES (r.class_id, r.gradebook_id,
            public.gradebook_column_group_display_name(r.base),
            public._gradebook_column_group_free_slug(r.gradebook_id, r.base),
            (r.group_index - 1)::integer,
            r.base)
    RETURNING id INTO v_id;
    INSERT INTO _cg_phase_one_groups (gradebook_id, group_index, group_id)
    VALUES (r.gradebook_id, r.group_index, v_id);
  END LOOP;
END $$;

UPDATE public.gradebook_columns gc
   SET gradebook_column_group_id = p.group_id
  FROM public.gradebook_column_legacy_groups r
  JOIN _cg_phase_one_groups p ON p.gradebook_id = r.gradebook_id
                             AND p.group_index = r.group_index
 WHERE gc.id = r.id;

UPDATE public.gradebook_columns gc
   SET position_in_group = sub.pos
  FROM (
    SELECT id,
           ROW_NUMBER() OVER (PARTITION BY gradebook_column_group_id
                              ORDER BY sort_order, id) - 1 AS pos
      FROM public.gradebook_columns
     WHERE gradebook_column_group_id IS NOT NULL
  ) sub
 WHERE gc.id = sub.id;

DO $$
DECLARE
  v_ungrouped     integer;
  v_order_diffs   integer;
  v_split_runs    integer;
  v_merged_runs   integer;
  v_name_diffs    integer;
  v_dupe_orders   integer;
BEGIN
  SELECT count(*) INTO v_ungrouped
    FROM public.gradebook_columns
   WHERE gradebook_column_group_id IS NULL OR position_in_group IS NULL;
  IF v_ungrouped > 0 THEN
    RAISE EXCEPTION 'backfill: % columns were left without a group or a position', v_ungrouped;
  END IF;

  SELECT count(*) INTO v_order_diffs
    FROM (
      SELECT ROW_NUMBER() OVER (PARTITION BY c.gradebook_id
                                ORDER BY c.sort_order, c.id) AS old_pos,
             ROW_NUMBER() OVER (PARTITION BY c.gradebook_id
                                ORDER BY g.sort_order, c.position_in_group, c.id) AS new_pos
        FROM public.gradebook_columns c
        JOIN public.gradebook_column_groups g ON g.id = c.gradebook_column_group_id
    ) t
   WHERE t.old_pos <> t.new_pos;
  IF v_order_diffs > 0 THEN
    RAISE EXCEPTION 'backfill: % columns would render in a different position than before', v_order_diffs;
  END IF;

  SELECT count(*) INTO v_split_runs
    FROM (
      SELECT count(DISTINCT gc.gradebook_column_group_id) AS n
        FROM public.gradebook_column_legacy_groups r
        JOIN public.gradebook_columns gc ON gc.id = r.id
       GROUP BY r.gradebook_id, r.group_index
    ) x
   WHERE x.n <> 1;

  SELECT count(*) INTO v_merged_runs
    FROM (
      SELECT count(DISTINCT (r.gradebook_id, r.group_index)) AS n
        FROM public.gradebook_column_legacy_groups r
        JOIN public.gradebook_columns gc ON gc.id = r.id
       GROUP BY gc.gradebook_column_group_id
    ) x
   WHERE x.n <> 1;

  IF v_split_runs > 0 OR v_merged_runs > 0 THEN
    RAISE EXCEPTION 'backfill: partition mismatch (% runs split, % runs merged)',
      v_split_runs, v_merged_runs;
  END IF;

  SELECT count(*) INTO v_name_diffs
    FROM public.gradebook_column_legacy_groups r
    JOIN public.gradebook_columns gc ON gc.id = r.id
    JOIN public.gradebook_column_groups g ON g.id = gc.gradebook_column_group_id
   WHERE g.name IS DISTINCT FROM public.gradebook_column_group_display_name(r.base);
  IF v_name_diffs > 0 THEN
    RAISE EXCEPTION 'backfill: % columns sit under a differently-named header than before', v_name_diffs;
  END IF;

  SELECT count(*) INTO v_dupe_orders
    FROM (
      SELECT gradebook_id, sort_order
        FROM public.gradebook_columns
       GROUP BY gradebook_id, sort_order
      HAVING count(*) > 1
    ) d;
  IF v_dupe_orders > 0 THEN
    RAISE WARNING 'backfill: % duplicate (gradebook_id, sort_order) pairs; browser order for those was undefined, SQL tie-broke on id', v_dupe_orders;
  END IF;

  RAISE NOTICE 'backfill phase one: reproduced the legacy grouping for % columns in % groups',
    (SELECT count(*) FROM public.gradebook_columns),
    (SELECT count(*) FROM public.gradebook_column_groups WHERE NOT is_default);
END $$;

