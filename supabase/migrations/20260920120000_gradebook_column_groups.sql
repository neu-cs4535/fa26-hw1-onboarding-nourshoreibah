CREATE OR REPLACE FUNCTION public.gradebook_column_base_group_name(p_slug text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN parts[1] = 'assignment' AND array_length(parts, 1) >= 3
      THEN parts[1] || '-' || parts[2]
    WHEN COALESCE(parts[1], '') = ''
      THEN 'other'
    ELSE parts[1]
  END
  FROM (SELECT string_to_array(COALESCE(p_slug, ''), '-') AS parts) s;
$$;

COMMENT ON FUNCTION public.gradebook_column_base_group_name(text) IS
  'Transcription of the legacy slug-prefix heuristic. Used by the one-time backfill and by new-column routing, never at render time.';

CREATE OR REPLACE FUNCTION public.gradebook_column_group_display_name(p_base text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN p_base = 'other' THEN 'Other'
    WHEN p_base LIKE 'assignment-%' THEN
      upper(left(split_part(p_base, '-', 2), 1)) || substr(split_part(p_base, '-', 2), 2)
    ELSE upper(left(p_base, 1)) || substr(p_base, 2)
  END;
$$;

