-- ---------------------------------------------------------------------------------------------
-- 4. The legacy heuristic, in SQL, used only by the backfill below
-- ---------------------------------------------------------------------------------------------
--
-- These two functions are a transcription of the `groupedColumns` memo. They exist so the
-- backfill can prove it reproduces what the browser did, and so routing a newly created column
-- can use the same rule the gradebook has always used. They do not run at render time.

CREATE OR REPLACE FUNCTION public.gradebook_column_base_group_name(p_slug text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  -- JS: const slugParts = col.slug.split("-");
  --     if (slugParts[0] === "assignment" && slugParts.length >= 3)
  --       baseGroupName = `${slugParts[0]}-${slugParts[1]}`;
  --     else baseGroupName = slugParts[0] || "other";
  --
  -- string_to_array('', '-') is {""} with array_length 1, which matches "".split("-") === [""].
  -- That empty first element is what the JS `|| "other"` catches.
  SELECT CASE
    WHEN parts[1] = 'assignment' AND array_length(parts, 1) >= 3
      THEN parts[1] || '-' || parts[2]
    WHEN COALESCE(parts[1], '') = ''
      THEN 'other'
    ELSE parts[1]
  END
  FROM (SELECT string_to_array(COALESCE(p_slug, ''), '-') AS parts) s;
$$;

COMMENT ON FUNCTION public.gradebook_column_base_group_name(text) IS
  'Transcription of the legacy slug-prefix heuristic. Used by the one-time backfill and by new-column routing, never at render time.';

CREATE OR REPLACE FUNCTION public.gradebook_column_group_display_name(p_base text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  -- JS uppercases index 0 only: `s.charAt(0).toUpperCase() + s.slice(1)`.
  -- Deliberately NOT initcap(), which would also uppercase after digits and underscores:
  -- initcap('mcq2go') is 'Mcq2Go', and initcap('a_b') is 'A_B'. The display name is what an
  -- instructor sees and renames from, so it has to match what they saw yesterday.
  SELECT CASE
    WHEN p_base = 'other' THEN 'Other'
    WHEN p_base LIKE 'assignment-%' THEN
      upper(left(split_part(p_base, '-', 2), 1)) || substr(split_part(p_base, '-', 2), 2)
    ELSE upper(left(p_base, 1)) || substr(p_base, 2)
  END;
$$;

