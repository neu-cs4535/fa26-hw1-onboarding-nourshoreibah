-- Gradebook column groups: make the group a row.
--
-- Until now a "column group" was a string operation in the browser. `groupedColumns` in
-- manage/gradebook/gradebookTable.tsx split each slug on '-', took the first token (with a
-- special case for `assignment-<type>-*`), and started a new group whenever sort_order skipped
-- a number. Four other sites re-derived the same prefix, two of them without the special case.
-- Nothing in the database knew a group existed.
--
-- This migration creates the table, backfills every gradebook that already exists, and moves
-- column ordering to two levels: groups are ordered within a gradebook, columns within their
-- group. The old global gradebook_columns.sort_order is dropped rather than reinterpreted, so
-- that any reader we missed fails loudly instead of returning a plausible but wrong order.
--
-- The slug parsing below runs exactly once, here. After this commit nothing parses a slug to
-- decide what a column belongs to; the foreign key says.
--
-- Companion migration 20260920120100 rewrites the ordering routines that depend on this shape.

-- ---------------------------------------------------------------------------------------------
-- 0. Preconditions
-- ---------------------------------------------------------------------------------------------

-- 20260408120001 already drained NULL sort_order and taught the assignment trigger to compute
-- one. Re-run the drain defensively, then assert, because the backfill's equivalence proof is
-- only meaningful if every column has a position. Note the JS heuristic treats NULL as 0 (it
-- does `col.sort_order ?? 0`), which sorts NULLs FIRST, while every SQL path in this repo uses
-- NULLS LAST. Rather than reproduce that disagreement we make it unreachable.
DO $$
DECLARE
  v_nulls integer;
BEGIN
  UPDATE public.gradebook_columns gc
     SET sort_order = sub.new_order
    FROM (
      SELECT id,
             ROW_NUMBER() OVER (PARTITION BY gradebook_id ORDER BY id) - 1
               + COALESCE((SELECT MAX(sort_order) + 1
                             FROM public.gradebook_columns x
                            WHERE x.gradebook_id = gradebook_columns.gradebook_id
                              AND x.sort_order IS NOT NULL), 0) AS new_order
        FROM public.gradebook_columns
       WHERE sort_order IS NULL
    ) sub
   WHERE gc.id = sub.id;

  SELECT count(*) INTO v_nulls FROM public.gradebook_columns WHERE sort_order IS NULL;
  IF v_nulls > 0 THEN
    RAISE EXCEPTION 'gradebook_column_groups: % columns still have a NULL sort_order', v_nulls;
  END IF;
END $$;

-- ---------------------------------------------------------------------------------------------
-- 1. The table
-- ---------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.gradebook_column_groups (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  class_id     bigint NOT NULL REFERENCES public.classes(id)    ON DELETE CASCADE,
  gradebook_id bigint NOT NULL REFERENCES public.gradebooks(id) ON DELETE CASCADE,
  name         text NOT NULL,
  slug         text NOT NULL,
  description  text,
  -- Position of this group among its gradebook's groups. Columns carry position_in_group;
  -- global display order is (group.sort_order, column.position_in_group, column.id).
  sort_order   integer NOT NULL,
  -- Share of the course total. NULL means "not weighted". Nothing computes from this until an
  -- instructor writes weighted_total() into a score_expression; see 20260920120100.
  weight       numeric,
  -- Exactly one per gradebook. Receives columns that no rule classifies, and is the target when
  -- a group is deleted. Cannot itself be deleted.
  is_default   boolean NOT NULL DEFAULT false,
  -- The legacy heuristic's baseGroupName. New columns whose slug derives this base are routed
  -- here automatically. NULL opts the group out of auto-routing, so an instructor who hand-curates
  -- a group keeps it hand-curated.
  auto_assign_slug_base text,
  CONSTRAINT gradebook_column_groups_slug_key
    UNIQUE (gradebook_id, slug),
  -- Referenced by the composite FK on gradebook_columns below. This is what makes it impossible
  -- to file a column under another gradebook's group.
  CONSTRAINT gradebook_column_groups_id_gradebook_key
    UNIQUE (id, gradebook_id),
  -- Deferrable: reordering groups swaps positions, which collides transiently.
  CONSTRAINT gradebook_column_groups_order_key
    UNIQUE (gradebook_id, sort_order) DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT gradebook_column_groups_weight_chk
    CHECK (weight IS NULL OR weight >= 0)
);

COMMENT ON TABLE public.gradebook_column_groups IS
  'A gradebook column group. Replaces the slug-prefix heuristic that used to compute groups in the browser on every render.';
COMMENT ON COLUMN public.gradebook_column_groups.sort_order IS
  'Position among this gradebook''s groups. Columns are ordered within a group by gradebook_columns.position_in_group.';
COMMENT ON COLUMN public.gradebook_column_groups.auto_assign_slug_base IS
  'Legacy slug base that routes new columns here. NULL means the group does not auto-receive columns.';
COMMENT ON COLUMN public.gradebook_column_groups.weight IS
  'Share of the course total, read by the weighted_total() expression function. NULL means unweighted.';

CREATE UNIQUE INDEX IF NOT EXISTS gradebook_column_groups_one_default
  ON public.gradebook_column_groups (gradebook_id) WHERE is_default;
CREATE INDEX IF NOT EXISTS gradebook_column_groups_auto_assign_idx
  ON public.gradebook_column_groups (gradebook_id, auto_assign_slug_base)
  WHERE auto_assign_slug_base IS NOT NULL;
CREATE INDEX IF NOT EXISTS gradebook_column_groups_class_id_idx
  ON public.gradebook_column_groups (class_id);

